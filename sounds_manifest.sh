# sounds_manifest.sh — (re)generate sounds.txt, the portal sound library manifest.
#
#   sh sounds_manifest.sh           rewrite sounds.txt from the files under sounds/
#   sh sounds_manifest.sh --check   change nothing; exit 1 if sounds.txt is out of date
#
# Layout:  sounds/<slot>/<name>.(mp3|ogg|wav)    <slot> = bg_music | insert_bg_music | coin_sound
# Optional display names / descriptions: sounds/names.txt (see SOUNDS.md).
# The output is deterministic (no timestamps), so --check is a plain comparison.
set -e
cd "$(dirname "$0")"
export LC_ALL=C

OUT="sounds.txt"
NAMES="sounds/names.txt"
SLOTS="bg_music insert_bg_music coin_sound"

emit() {
    echo "# sounds.txt — portal sound library manifest."
    echo "# GENERATED by sounds_manifest.sh from the files under sounds/ — do not edit by hand."
    echo "# \"slot\" decides which selector offers a sound: bg_music | insert_bg_music | coin_sound."
    for slot in $SLOTS; do
        [ -d "sounds/$slot" ] || continue
        for p in "sounds/$slot"/*; do
            [ -f "$p" ] || continue
            f=${p##*/}
            case "$f" in *.mp3|*.ogg|*.wav) ;; *) continue ;; esac
            stem=${f%.*}
            case "$stem" in
                ""|[!a-z0-9]*|*[!a-z0-9_-]*)
                    echo "sounds_manifest: bad file name '$p' — use lowercase a-z, 0-9, _ and - (starting with a letter or digit)" >&2
                    exit 2 ;;
            esac
            meta=$(grep -m1 "^$slot/$stem=" "$NAMES" 2>/dev/null | sed 's/^[^=]*=//') || true
            if [ -n "$meta" ]; then
                name=${meta%%|*}
                case "$meta" in *'|'*) desc=${meta#*|} ;; *) desc="" ;; esac
            else
                name=$(printf '%s' "$stem" | tr '_-' '  ' | awk '{ print toupper(substr($0, 1, 1)) substr($0, 2) }')
                desc=""
            fi
            sha=$(sha256sum "$p" | awk '{ print $1 }')
            size=$(wc -c < "$p" | tr -d ' ')
            echo ""
            echo "id=$stem"
            echo "slot=$slot"
            echo "name=$name"
            echo "file=$slot/$f"
            echo "size=$size"
            echo "sha256=$sha"
            [ -n "$desc" ] && echo "description=$desc"
        done
    done
    return 0
}

case "$1" in
    --check)
        tmp=$(mktemp)
        trap 'rm -f "$tmp"' EXIT
        emit > "$tmp"
        if cmp -s "$tmp" "$OUT"; then
            echo "$OUT is up to date."
        else
            echo "$OUT is out of date — run: sh sounds_manifest.sh" >&2
            exit 1
        fi ;;
    "")
        # A bad file name aborts emit half-way; don't leave the partial file behind.
        trap 'rm -f "$OUT.tmp"' EXIT
        emit > "$OUT.tmp"
        mv "$OUT.tmp" "$OUT"
        echo "wrote $OUT ($(grep -c '^id=' "$OUT") sounds)" ;;
    *)
        echo "usage: sh $0 [--check]" >&2
        exit 2 ;;
esac
